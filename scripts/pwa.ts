// pattern-check: skip — one build-only Vite plugin writing the app-shell
// service worker from the emitted file list.
//
// The web app works offline: production builds replace public/pkg-sw.js (which
// in dev only serves delivered builder packages) with a service worker that
// also precaches the app shell, answers navigations from the cached
// index.html when offline, and keeps every hashed asset it fetches. A new
// version waits until the page asks it to take over (see
// src/renderer/src/lib/pwa.ts), so a session never mixes two builds.
import { createHash } from 'node:crypto'
import { readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, sep } from 'node:path'
import type { Plugin } from 'vite'

const SW_FILE = 'pkg-sw.js'
/** Monaco and its workers (only the JSON panels use them) are cached on first
 *  use instead; so is anything unexpectedly big. */
const PRECACHE_MAX_BYTES = 3 * 1024 * 1024
const LAZY = /^assets\/(monaco-|[a-z]+\.worker-)/
const SKIP = [
    /^_pkg\//,
    /^_seed\//,
    /\.map$/,
    /^_headers$/,
    /^_redirects$/,
    new RegExp(`^${SW_FILE}$`),
]

function walk(dir: string, root: string): { path: string; bytes: number }[] {
    return readdirSync(dir).flatMap((name) => {
        const full = join(dir, name)
        const stat = statSync(full)
        if (stat.isDirectory()) return walk(full, root)
        return [
            {
                path: relative(root, full).split(sep).join('/'),
                bytes: stat.size,
            },
        ]
    })
}

export function precacheList(outDir: string): string[] {
    return walk(outDir, outDir)
        .filter(
            (f) =>
                !SKIP.some((re) => re.test(f.path)) &&
                !LAZY.test(f.path) &&
                f.bytes <= PRECACHE_MAX_BYTES,
        )
        .map((f) => `/${f.path}`)
        .sort()
}

export function serviceWorkerSource(urls: readonly string[]): string {
    const version = createHash('sha256')
        .update(urls.join('\n'))
        .digest('hex')
        .slice(0, 12)
    return `// Generated by scripts/pwa.ts — the Remappr web app shell.
const VERSION = ${JSON.stringify(version)}
const SHELL = 'remappr-shell-' + VERSION
const ASSETS = 'remappr-assets-' + VERSION
const PACKAGES = 'remappr-pkg-v1'
const PRECACHE = ${JSON.stringify(urls)}

self.addEventListener('install', (event) => {
    event.waitUntil(caches.open(SHELL).then((c) => c.addAll(PRECACHE)))
})

self.addEventListener('activate', (event) => {
    event.waitUntil(
        caches
            .keys()
            .then((keys) =>
                Promise.all(
                    keys
                        .filter((k) => /^remappr-(shell|assets)-/.test(k) && k !== SHELL && k !== ASSETS)
                        .map((k) => caches.delete(k)),
                ),
            )
            .then(() => self.clients.claim()),
    )
})

self.addEventListener('message', (event) => {
    if (event.data === 'SKIP_WAITING') self.skipWaiting()
})

async function fromCaches(path) {
    for (const name of [SHELL, ASSETS]) {
        const hit = await (await caches.open(name)).match(path)
        if (hit) return hit
    }
    return undefined
}

self.addEventListener('fetch', (event) => {
    const req = event.request
    const url = new URL(req.url)
    if (req.method !== 'GET' || url.origin !== self.location.origin) return
    if (url.pathname.startsWith('/_pkg/')) {
        event.respondWith(caches.open(PACKAGES).then((c) => c.match(url.pathname)).then((hit) => hit ?? fetch(req)))
        return
    }
    if (req.mode === 'navigate') {
        event.respondWith(fetch(req).catch(() => fromCaches('/index.html').then((hit) => hit ?? Response.error())))
        return
    }
    if (url.pathname.startsWith('/assets/')) {
        // Hashed, immutable: the cache answers, the network fills it.
        event.respondWith(
            fromCaches(url.pathname).then(
                (hit) =>
                    hit ??
                    fetch(req).then((res) => {
                        if (res.ok) caches.open(ASSETS).then((c) => c.put(url.pathname, res.clone()))
                        return res
                    }),
            ),
        )
        return
    }
    event.respondWith(fetch(req).catch(() => fromCaches(url.pathname).then((hit) => hit ?? Response.error())))
})
`
}

export function pwaPlugin(): Plugin {
    let outDir = ''
    return {
        name: 'remappr-pwa',
        apply: 'build',
        configResolved(config) {
            outDir = config.build.outDir
        },
        closeBundle() {
            writeFileSync(
                join(outDir, SW_FILE),
                serviceWorkerSource(precacheList(outDir)),
            )
        },
    }
}
